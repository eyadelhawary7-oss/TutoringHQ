const en = JSON.parse(readFileSync('messages/en.json', 'utf8'))
const ar = JSON.parse(readFileSync('messages/ar.json', 'utf8'))

if (!en.admin || typeof en.admin !== 'object') en.admin = {}
if (!ar.admin || typeof ar.admin !== 'object') ar.admin = {}

for (const [k, v] of Object.entries(EN_EXTRA)) {
  if (!(k in en.admin)) en.admin[k] = v
}
for (const [k, v] of Object.entries(AR_EXTRA)) {
  if (!(k in ar.admin)) ar.admin[k] = v
}

writeFileSync('messages/en.json', JSON.stringify(en, null, 2))
writeFileSync('messages/ar.json', JSON.stringify(ar, null, 2))
console.log('Admin keys extended.')
