--   - Postgres refuses a direct `SELECT public.sessions_derive_center_id()`
--     with 42809 ("trigger functions can only be called as triggers"),
--     regardless of who holds EXECUTE.
--   - Revoking does not disable the trigger: Postgres checks EXECUTE at
--     CREATE TRIGGER time, not at fire time.
-- The problem is not exploitability. The problem is that the committed comment
-- and the live catalog disagree, and a reader auditing SECURITY DEFINER
-- surfaces would tick this one off as closed when it is not.
