BEGIN;

-- Idempotent by nature: REVOKE on a privilege that is not held is a no-op, so
-- this is safe to re-run and safe on a partial apply (§5.2 of the prior file).
REVOKE ALL ON FUNCTION public.sessions_derive_center_id() FROM anon, authenticated;

COMMIT;

